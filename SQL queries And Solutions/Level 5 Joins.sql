61. Display customer names along with their order IDs.

select c.customername,o.Orderid
from customers c  join orders o
on c.customerid = o.customerid

62. Display all customers, including those who have never placed an order.

select c.* 
from customers c left join orders o
on c.customerid=o.customerid

63. Find customers who have never placed an order.

select c.*
from customers c left join orders o
on c.customerid = o.customerid
where o.orderid is null

64. Display all orders along with customer names and order dates.

select o.*,c.customername
from orders o left join customers c
on o.customerid = c.customerid

65. Display order IDs with product names and quantities.

select o.orderid,p.productname,o.quantity
from orderdetails o join products p
on o.productid=p.productid

66. Display product names with their category names.

